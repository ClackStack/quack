#!/usr/bin/env bash
# Write a Homebrew formula for a release, from its SHA256SUMS:
#
#   scripts/homebrew.sh <version> <SHA256SUMS> [out-dir]
#
# Writes quack.rb (binary and defaults bundle) for a tap repository (Formula/ in
# github.com/<owner>/homebrew-quack). It points at the release's archives for macOS and
# Linux, on Intel and ARM.
set -euo pipefail

version=${1:?usage: homebrew.sh <version> <SHA256SUMS> [out-dir]}
version=${version#v}
sums=${2:?usage: homebrew.sh <version> <SHA256SUMS> [out-dir]}
out=${3:-dist}
repo=https://github.com/ClackStack/quack
mkdir -p "$out"

sha() {
  local sum
  sum=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$sum" ] || { echo "homebrew.sh: $1 is not in $sums" >&2; exit 1; }
  echo "$sum"
}

# Command substitution would swallow a failure from sha(), so check the sums up front.
for t in aarch64-apple-darwin x86_64-apple-darwin aarch64-unknown-linux-musl x86_64-unknown-linux-musl; do
  awk -v f="quack-$t.tar.gz" '$2 == f || $2 == "*" f { found = 1 } END { exit !found }' "$sums" \
    || { echo "homebrew.sh: quack-$t.tar.gz is not in $sums" >&2; exit 1; }
done

url=$repo/releases/download/v$version
cat <<EOF > "$out/quack.rb"
# Generated by scripts/homebrew.sh for quack $version.
class Quack < Formula
  desc "Terminal coding agent for open-weight models"
  homepage "$repo"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$url/quack-aarch64-apple-darwin.tar.gz"
      sha256 "$(sha "quack-aarch64-apple-darwin.tar.gz")"
    end
    on_intel do
      url "$url/quack-x86_64-apple-darwin.tar.gz"
      sha256 "$(sha "quack-x86_64-apple-darwin.tar.gz")"
    end
  end

  on_linux do
    on_arm do
      url "$url/quack-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$(sha "quack-aarch64-unknown-linux-musl.tar.gz")"
    end
    on_intel do
      url "$url/quack-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$(sha "quack-x86_64-unknown-linux-musl.tar.gz")"
    end
  end

  def install
    bin.install "bin/quack"
    # The binary looks for its bundle in <prefix>/share/quack/defaults.
    (share/"quack").install "share/quack/defaults"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/quack --version")
  end
end
EOF
echo "wrote $out/quack.rb"
